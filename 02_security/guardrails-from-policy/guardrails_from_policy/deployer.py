"""Deploy or update a Bedrock Guardrail from a GuardrailConfig.

Strategy:
  1. List existing guardrails by name.
  2. If none found → CreateGuardrail.
  3. If found → UpdateGuardrail on the latest version draft.
  4. Create a new version so it can be attached to a model invocation.
"""

from __future__ import annotations

from dataclasses import dataclass

from .guardrail_builder import GuardrailConfig


@dataclass
class DeployResult:
    guardrail_id: str
    guardrail_arn: str
    version: str
    created: bool  # True = created, False = updated


def deploy_guardrail(
    config: GuardrailConfig,
    *,
    region: str = "us-west-2",
    kms_key_id: str | None = None,
    tags: dict[str, str] | None = None,
    dry_run: bool = False,
) -> DeployResult:
    """Create or update a Bedrock Guardrail matching `config`.

    Args:
        config:     GuardrailConfig produced by build_guardrail_config().
        region:     AWS region.
        kms_key_id: Optional KMS key ARN/ID for encrypting the guardrail.
        tags:       Optional tags to attach (key→value).
        dry_run:    If True, print what would be done and return a fake result.

    Returns:
        DeployResult with guardrail_id, ARN, version string, and a created flag.
    """
    if dry_run:
        return _dry_run(config)

    import boto3
    client = boto3.client("bedrock", region_name=region)

    existing_id = _find_existing(client, config.name)
    kwargs = config.as_boto3_kwargs()

    if kms_key_id:
        kwargs["kmsKeyId"] = kms_key_id
    if tags:
        kwargs["tags"] = [{"key": k, "value": v} for k, v in tags.items()]

    if existing_id is None:
        resp = client.create_guardrail(**kwargs)
        guardrail_id = resp["guardrailId"]
        created = True
    else:
        # UpdateGuardrail doesn't accept tags or kmsKeyId at update time
        update_kwargs = {k: v for k, v in kwargs.items() if k not in ("tags", "kmsKeyId")}
        client.update_guardrail(guardrailIdentifier=existing_id, **update_kwargs)
        guardrail_id = existing_id
        created = False

    # Create a numbered version so it can be referenced by alias/invocation
    ver_resp = client.create_guardrail_version(
        guardrailIdentifier=guardrail_id,
        description=f"Generated by guardrails-from-policy: {config.description[:100]}",
    )
    version = ver_resp["version"]

    # Fetch ARN
    detail = client.get_guardrail(
        guardrailIdentifier=guardrail_id,
        guardrailVersion=version,
    )
    return DeployResult(
        guardrail_id=guardrail_id,
        guardrail_arn=detail["guardrailArn"],
        version=version,
        created=created,
    )


def _find_existing(client, name: str) -> str | None:
    """Return the guardrailId of the first guardrail with this name, or None."""
    paginator = client.get_paginator("list_guardrails")
    for page in paginator.paginate():
        for g in page.get("guardrails", []):
            if g.get("name") == name:
                return g["guardrailId"]
    return None


def _dry_run(config: GuardrailConfig) -> DeployResult:
    import json, sys
    print("\n[DRY RUN] Would call bedrock.create_guardrail with:")
    print(json.dumps(config.as_dict(), indent=2))
    return DeployResult(
        guardrail_id="dry-run-id",
        guardrail_arn="arn:aws:bedrock:us-west-2:000000000000:guardrail/dry-run-id",
        version="DRAFT",
        created=True,
    )
